do
	-- Prefer the engine's virtual path; fall back to the file next to this module
	-- so the dofile/loadfile unit harnesses exercise the shipped table too
	-- (the same harness pattern CheckerTokens.loadStyle uses).
	local function loadHeights(path)
		if type(path)~='string' or type(loadfile)~='function' then return nil end
		if fs and fs.exists and not fs.exists(path) then return nil end
		local chunk=loadfile(path)
		if not chunk then return nil end
		local ok,data=pcall(chunk)
		if ok and type(data)=='table' then return data end
	end
	local heights=loadHeights(M.standee_heights_path)
	if not heights then
		local source=debug.getinfo(1,'S').source
		if type(source)=='string' and source:sub(1,1)=='@' then
			local dir=source:sub(2):match('^(.*[/\\])') or './'
			heights=loadHeights(dir..'../../../data/token-standee-heights.lua')
		end
