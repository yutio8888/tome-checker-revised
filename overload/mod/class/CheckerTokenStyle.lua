-- Height cap in cells for one identity, read statically from the committed
-- native-tall table (never from the live actor). nil means the id is not
-- natively tall and keeps the flat token; 1.0 is the flat marker.
function M.standeeHeight(id)
	local override=id and M.standee_height_override[id]
	if type(override)=='number' then return override end
	return id and M.standee_heights[id] or nil
end

-- Standees only at tiles >= M.standee_min_cell pixels.
function M.standeeCellAllowed(cell)
	local n=tonumber(cell)
	return n~=nil and n>=M.standee_min_cell
end

-- Pure standee geometry. box is the creature alpha bbox on the layer canvas
-- {"left","top","right","bottom",...} with right/bottom exclusive, measured by
-- tools/build_token_layers.py. canvas is that file's square size in px (the
-- geometry entry's canvas field; 256 for standee layers). box.body_top is the
-- y of the top of the BODY (head, horns, helmet, hair, raised arms and wings
-- count; raised weapons, staves, orbs and particles do not); it defaults to the
-- alpha top when the geometry has no reviewed value. height is the height cap
-- in cells from M.standeeHeight. Feet-to-body_top is scaled to the cap, so a
-- raised weapon above body_top may stick out above; the whole art is still
-- capped at M.standee_width cells wide, and the uniform scale shrinks when that
-- cap binds. Returns the screen quad (left,top,size) that draws the whole
-- canvas at one uniform scale, or nil when box or height is invalid.
function M.standeeQuad(cell,box,canvas,disc_cx,disc_cy,disc_d,height)
	if type(box)~='table' then return nil end
	local left,top,right,bottom=box.left,box.top,box.right,box.bottom
	if type(left)~='number' or type(top)~='number' or type(right)~='number' or type(bottom)~='number' then return nil end
	local bw,bh=right-left,bottom-top
	if bw<=0 or bh<=0 then return nil end
	local cap=tonumber(height)
	if not cap then return nil end
	local body_top=tonumber(box.body_top) or top
	local body_h=bottom-body_top
	if body_h<=0 then return nil end
	local scale=math.min(cap*cell/body_h,M.standee_width*cell/bw)
	local size=(canvas or 128)*scale
	return disc_cx-((left+right)/2)*scale,(disc_cy+M.standee_feet*disc_d/2)-bottom*scale,size
end

-- Native shader-aura geometry for a standee, in map-cell units relative to the
-- actor's own cell origin (exactly how the engine chains add_mos on the
-- display Entity). The native aura is built from selfbase.image -- for a token
-- that is the flat disc -- at a fixed display_h=2 / display_y=-1 box, so it hugs
-- the own cell instead of wrapping the upright figure. For a standee the aura
-- must use the standee layer image at the standee quad instead. Deriving the
-- cell-unit box here keeps it identical to M.standeeQuad at any tile size:
--   screen box = (cell*dx, cell*dy, cell*w, cell*h).
-- R46: the aura texture can be non-square (128x256 for a tall body). The quad
-- aspect must equal the texture aspect, so canvas_w/canvas_h are separate and
-- the function returns display_x, display_y, display_w, display_h or nil. The
-- factor is unchanged (cells per aura-texture pixel).
function M.standeeAuraQuad(box,canvas_w,canvas_h,height)
	if type(box)~='table' then return nil end
	local left,top,right,bottom=box.left,box.top,box.right,box.bottom
	if type(left)~='number' or type(top)~='number' or type(right)~='number' or type(bottom)~='number' then return nil end
	local bw,bh=right-left,bottom-top
	if bw<=0 or bh<=0 then return nil end
	local cap=tonumber(height)
	if not cap then return nil end
	local cw,ch=tonumber(canvas_w),tonumber(canvas_h)
	if not cw or cw<=0 or not ch or ch<=0 then return nil end
	-- Body-only height, exactly like M.standeeQuad, so the aura follows the
	-- creature quad after the body_top change. The aura box records its own
	-- body_top (the layer body_top mapped onto the aura canvas).
	local body_top=tonumber(box.body_top) or top
	local body_h=bottom-body_top
	if body_h<=0 then return nil end
	-- cells of screen per aura-texture pixel; isotropic, so one factor for both
	-- axes and the quad aspect matches canvas_w:canvas_h.
	local factor=math.min(cap/body_h,M.standee_width/bw)
	local w,h=cw*factor,ch*factor
	if w<=0 or h<=0 then return nil end
	return .5-((left+right)/2)*factor,
	 .5+M.standee_feet*M.token_diameter/2-bottom*factor,
	 w,h
end

function M.scale(size,tile)
 -- One board piece, one diameter. size_category and tile size describe the
 -- creature and the viewport, not the playing piece: tiering them made
 -- neighbouring tokens differ by 7px at 64px cells and read as misaligned.
 -- The arguments are kept so existing call sites stay unchanged.
 return M.token_diameter/M.art_occupancy
end

function M.relation(actor,viewer,reaction)
 return actor==viewer and 'player' or reaction<0 and 'enemy' or reaction>0 and 'friend' or 'neutral'
end

function M.geometry(x,y,cell,scale)
 -- AI artwork occupies M.art_occupancy of its square. The faction ring lane
 -- sits outside it; M.ring_lane is the whole diameter addition so the mask
 -- canvas is exactly the outer edge of the ring.
 local diameter=cell*(M.art_occupancy*scale+M.ring_lane)
 return {x=x+(cell-diameter)/2,y=y+(cell-diameter)/2,d=diameter,
  cx=x+cell/2,cy=y+cell/2,cell=cell}
end

-- Native tactical life bar, reproduced instead of copied from the engine so a
-- board token shows exactly what the game draws when tokens are off. All
-- geometry, thresholds, RGB and alphas cite game/modules/tome/class/Actor.lua:
--   mode choice   : 1303-1308 (small frame only with view_faction + always_target~='old')
--   small side    : 1017-1036 (friend left / enemy right, dy stacked from the bottom)
--   small bottom  : 1104-1121 (dx grows left to right)
--   big side      : 1198-1214 (literal 3px inset)
--   big bottom    : 1215-1229 (literal 3px inset)
-- tests/native_lifebar.lua parses that file and asserts these numbers, so this
-- table cannot silently drift away from the engine.
M.native_life_bar={
 small_bottom={sx=.078125,dx=.90625,sy=.9375,dy=.984375},
 small_side={sx=.015625,dx=.0625,sy=.03125,dy=.953125,enemy_sx=.9375},
 big={inset=3,side_dw=.1,bottom_dh=.1},
 bands={
  {min=.75,track={129,180,57},fill={50,220,77}},
  {min=.5,track={175,175,10},fill={240,252,35}},
  {min=.25,track={185,88,0},fill={255,156,21}},
  {min=-math.huge,track={167,55,39},fill={235,0,0}},
 },
 track_alpha=128,fill_alpha=255,epsilon=.0001,
}

-- Native fraction: math.max(0,life)/max_life + 0.0001 (Actor.lua band lines).
function M.nativeLifeFraction(actor)
 local max=actor.max_life or 0
 if max<=0 then return 0 end
 return math.max(0,actor.life or 0)/max+M.native_life_bar.epsilon
end

-- Choose the exact native bar variant. nil means the engine draws no bar:
-- with no game.always_target the border alone is drawn, never a bar.
function M.nativeBarMode(map)
 if not (map and game and game.always_target) then return nil end
 local side=config and config.settings and config.settings.tome and config.settings.tome.small_frame_side
 -- Native: small frame only with view_faction + always_target~='old'; every
 -- other truthy always_target uses the big frame (whose bar does not need
 -- view_faction). No always_target means the border alone, never a bar.
 if map.view_faction and game.always_target~='old' then return side and 'small-side' or 'small-bottom' end
 return side and 'big-side' or 'big-bottom'
end

-- Draw only the native tactical life bar (no native border tiles): the board
-- token's thin faction ring replaces those. mode is one of small-bottom,
-- small-side, big-bottom, big-side; side_enemy only moves the small side bar.
function M.nativeLifeBar(actor,x,y,w,h,mode,side_enemy)
 local b=M.native_life_bar
 local lp=M.nativeLifeFraction(actor)
 local band=b.bands[#b.bands]
 for _,candidate in ipairs(b.bands) do if lp>candidate.min then band=candidate break end end
 local function quad(qx,qy,qw,qh,c,a) core.display.drawQuad(qx,qy,qw,qh,c[1],c[2],c[3],a) end
 if mode=='small-bottom' then
  local g=b.small_bottom
  local sx,dx,sy,dy=w*g.sx,w*g.dx-w*g.sx,h*g.sy,h*g.dy-h*g.sy
  quad(x+sx,y+sy,dx,dy,band.track,b.track_alpha)
  quad(x+sx,y+sy,dx*lp,dy,band.fill,b.fill_alpha)
 elseif mode=='small-side' then
  local g=b.small_side
  local sx=side_enemy and w*g.enemy_sx or w*g.sx
  local dx,sy,dy=w*g.dx-w*g.sx,h*g.sy,h*g.dy-h*g.sy
  quad(x+sx,y+sy,dx,dy,band.track,b.track_alpha)
  quad(x+sx,y+sy+dy*(1-lp),dx,dy*lp,band.fill,b.fill_alpha)
 elseif mode=='big-side' then
  local dw,inset=w*b.big.side_dw,b.big.inset
  quad(x+inset,y+inset,dw,h-2*inset,band.track,b.track_alpha)
  quad(x+inset,y+inset+(h-2*inset)*(1-lp),dw,(h-2*inset)*lp,band.fill,b.fill_alpha)
 elseif mode=='big-bottom' then
  local dh,inset=h*b.big.bottom_dh,b.big.inset
  quad(x+inset,y+h-dh,w-2*inset,dh,band.track,b.track_alpha)
  quad(x+inset,y+h-dh,(w-2*inset)*lp,dh,band.fill,b.fill_alpha)
 end
end

-- Rank badge size in px for one map cell. Above 16px this keeps the historic
-- 12x9 floor and proportional size. At <=16px that floor covered most of a
-- 16px token, so the badge is scaled to the cell instead (6x5 at 16px).
function M.badgeSize(cell)
 local n=tonumber(cell) or 0
 if n<=16 then
  return math.max(4,math.floor(n*.38+.5)),math.max(3,math.floor(n*.30+.5))
 end
 return math.max(12,n*.23),math.max(9,n*.18)
end

function M.rankBadge(rank)
 -- Critter (1), normal (2) and elite (3) intentionally share an unmarked base.
 -- Elite boss (5) is a separate native rank and retains its crown.
 if rank==3.2 then return 'rare' end
 if rank==3.5 then return 'unique' end
 if rank==4 then return 'boss' end
 if rank==5 then return 'elite_boss' end
 if rank==10 then return 'god' end
end

